import { isDeepStrictEqual } from 'node:util';
import type { OpenAPIObject } from '@nestjs/swagger';
import type { JSONSchema } from 'zod/v4/core';
import {
  DEFS_KEY,
  EMPTY_TYPE_KEY,
  PARENT_ADDITIONAL_PROPERTIES_KEY,
  PARENT_HAS_REFS_KEY,
  PARENT_ID_KEY,
  PARENT_METADATA_KEY,
  SELF_REQUIRED_KEY,
  TYPE_KEY,
  UNWRAP_ROOT_KEY,
} from './const.js';
import {
  decodeJsonPointerSegment,
  encodeJsonPointerSegment,
  fixAllRefs,
  walkJsonSchema,
} from './utils.js';

type DtoSchema = NonNullable<
  NonNullable<OpenAPIObject['components']>['schemas']
>[string];
type PathItem = NonNullable<OpenAPIObject['paths']>[string];
type OperationObject = NonNullable<PathItem['get']>;
type OpenAPIParameter = NonNullable<OperationObject['parameters']>[number];

const HTTP_METHODS = [
  'get',
  'put',
  'post',
  'delete',
  'options',
  'head',
  'patch',
  'trace',
] as const;

const EXTRA_PARAM_SCHEMA_KEYS = [
  'const',
  'prefixItems',
  'propertyNames',
  'examples',
] as const;

/**
 * Post-processes the OpenAPI document generated by `SwaggerModule.createDocument`
 * for `createZodDto` classes:
 * 1. Cleans up synthetic `type` markers and restores OpenAPI 3.1 type arrays
 * 2. Renames schemas with `.meta({ id })` and updates `$ref`s in paths and responses
 * 3. Registers nested `$defs`/`definitions` schemas in `components.schemas`
 * 4. Unwraps non-object root DTOs (arrays, unions, scalars, empty objects)
 * 5. Resolves recursive `$ref`s and cleans up query/path parameters
 */
export function cleanupOpenApiDoc(doc: OpenAPIObject): OpenAPIObject {
  const schemas: Record<string, DtoSchema> = {};
  const renames: Record<string, string> = {};

  for (const [oldSchemaName, oldOpenapiSchema] of Object.entries(
    doc.components?.schemas || {},
  )) {
    const { newSchema, newSchemaName, additionalNewSchemas } = cleanupSchema({
      oldSchemaName,
      oldOpenapiSchema,
    });

    for (const [additionalSchemaName, additionalSchema] of Object.entries(
      additionalNewSchemas,
    )) {
      registerSchema(schemas, additionalSchemaName, additionalSchema);
    }

    if (oldSchemaName !== newSchemaName) {
      renames[oldSchemaName] = newSchemaName;
    }

    registerSchema(schemas, newSchemaName, newSchema);
  }

  if (Object.keys(renames).length > 0) {
    for (const schema of Object.values(schemas)) {
      renameSchemaRefs(schema, renames);
    }
  }

  const paths = structuredClone(doc.paths);
  for (const pathItem of Object.values(paths)) {
    for (const method of HTTP_METHODS) {
      const methodObject = pathItem[method];
      if (!methodObject) continue;

      fixRefsInOperation({ methodObject, renames });

      if (!methodObject.parameters) continue;

      for (let i = 0; i < methodObject.parameters.length; i++) {
        const parameter = fixParameter(methodObject.parameters[i]);
        const rawParam = parameter as unknown as Record<string, unknown>;

        if (SELF_REQUIRED_KEY in rawParam) {
          if (
            'schema' in parameter &&
            parameter.in === 'query' &&
            typeof parameter.style === 'undefined' &&
            parameter.schema &&
            'type' in parameter.schema &&
            parameter.schema.type === 'object'
          ) {
            parameter.style = 'deepObject';
          }

          if ('schema' in parameter) {
            if (
              Array.isArray(parameter.required) &&
              parameter.schema &&
              'type' in parameter.schema &&
              parameter.schema.type === 'object' &&
              typeof parameter.schema.required === 'undefined'
            ) {
              parameter.schema.required = parameter.required;
            }
            parameter.required = Boolean(rawParam[SELF_REQUIRED_KEY]);
          }

          delete rawParam[SELF_REQUIRED_KEY];
        }

        if (DEFS_KEY in rawParam) {
          const defs = rawParam[DEFS_KEY] as Record<
            string,
            JSONSchema.BaseSchema
          >;
          delete rawParam[DEFS_KEY];

          for (const [defSchemaId, defSchema] of Object.entries(defs)) {
            let fixedDef: JSONSchema.BaseSchema;
            try {
              fixedDef = fixAllRefs({ schema: defSchema });
            } catch (err) {
              if (
                err instanceof Error &&
                err.message.startsWith('[fixAllRefs]')
              ) {
                throw new Error(
                  '[cleanupOpenApiDoc] Recursive schemas are not supported for parameters',
                  { cause: err },
                );
              }
              throw err;
            }

            registerSchema(schemas, defSchemaId, fixedDef as DtoSchema);
          }
        }

        if ('schema' in parameter && parameter.schema) {
          renameSchemaRefs(parameter.schema, renames);
        }

        methodObject.parameters[i] = parameter;
      }
    }
  }

  return {
    ...doc,
    paths,
    components: {
      ...doc.components,
      schemas,
    },
  };
}

function registerSchema(
  schemaRegistry: Record<string, DtoSchema>,
  schemaName: string,
  schema: DtoSchema,
) {
  if (
    Object.hasOwn(schemaRegistry, schemaName) &&
    !isDeepStrictEqual(schemaRegistry[schemaName], schema)
  ) {
    throw new Error(
      `[cleanupOpenApiDoc] Found multiple schemas with name \`${schemaName}\`. Please review your schemas to ensure that you are not using the same schema name for different schemas.`,
    );
  }

  schemaRegistry[schemaName] = schema;
}

function renameSchemaRefs(schema: unknown, renames: Record<string, string>) {
  if (
    !schema ||
    typeof schema !== 'object' ||
    Object.keys(renames).length === 0
  )
    return;
  walkJsonSchema(schema as JSONSchema.BaseSchema, (node) => {
    if (
      typeof node.$ref === 'string' &&
      node.$ref.startsWith('#/components/schemas/')
    ) {
      const oldName = decodeJsonPointerSegment(
        node.$ref.slice('#/components/schemas/'.length),
      );
      if (Object.hasOwn(renames, oldName)) {
        node.$ref = `#/components/schemas/${encodeJsonPointerSegment(renames[oldName])}`;
      }
    }
    return node;
  });
}

function fixRefsInOperation({
  methodObject,
  renames,
}: {
  methodObject: OperationObject;
  renames: Record<string, string>;
}) {
  if (Object.keys(renames).length === 0) return;

  if (methodObject.requestBody && 'content' in methodObject.requestBody) {
    for (const mediaType of Object.values(
      methodObject.requestBody.content || {},
    )) {
      renameSchemaRefs(mediaType.schema, renames);
    }
  }

  for (const response of Object.values(methodObject.responses || {})) {
    if (response && 'content' in response) {
      for (const mediaType of Object.values(response.content || {})) {
        renameSchemaRefs(mediaType.schema, renames);
      }
    }
  }
}

function cleanupSchema({
  oldSchemaName,
  oldOpenapiSchema,
}: {
  oldSchemaName: string;
  oldOpenapiSchema: DtoSchema;
}) {
  const additionalNewSchemas: Record<string, DtoSchema> = {};
  if (!('type' in oldOpenapiSchema) || oldOpenapiSchema.type !== 'object') {
    return {
      newSchema: oldOpenapiSchema,
      newSchemaName: oldSchemaName,
      additionalNewSchemas,
    };
  }

  let newSchemaName = oldSchemaName;
  let addedDefs = false;
  let hasRefs = false;
  const defRenames: Record<string, string> = {};

  let newOpenapiSchema = structuredClone(oldOpenapiSchema);

  for (const propertySchema of Object.values(
    newOpenapiSchema.properties || {},
  )) {
    const prop = propertySchema as Record<string, unknown>;

    if (SELF_REQUIRED_KEY in prop) {
      delete prop[SELF_REQUIRED_KEY];
      if ('selfRequired' in prop) {
        delete prop.selfRequired;
      }
    }

    if (PARENT_HAS_REFS_KEY in prop) {
      hasRefs = Boolean(prop[PARENT_HAS_REFS_KEY]);
      delete prop[PARENT_HAS_REFS_KEY];
    }

    if (EMPTY_TYPE_KEY in prop) {
      if (prop[EMPTY_TYPE_KEY]) {
        delete prop.type;
      }
      delete prop[EMPTY_TYPE_KEY];
    }

    if (TYPE_KEY in prop) {
      prop.type = prop[TYPE_KEY];
      delete prop[TYPE_KEY];
    }

    if (PARENT_ID_KEY in prop && typeof prop[PARENT_ID_KEY] === 'string') {
      newSchemaName = prop[PARENT_ID_KEY];
      delete prop[PARENT_ID_KEY];
    }

    if (
      PARENT_METADATA_KEY in prop &&
      prop[PARENT_METADATA_KEY] &&
      typeof prop[PARENT_METADATA_KEY] === 'object'
    ) {
      Object.assign(newOpenapiSchema, prop[PARENT_METADATA_KEY]);
      delete prop[PARENT_METADATA_KEY];
    }

    if (
      PARENT_ADDITIONAL_PROPERTIES_KEY in prop &&
      typeof prop[PARENT_ADDITIONAL_PROPERTIES_KEY] === 'boolean'
    ) {
      newOpenapiSchema.additionalProperties =
        prop[PARENT_ADDITIONAL_PROPERTIES_KEY];
      delete prop[PARENT_ADDITIONAL_PROPERTIES_KEY];
    }

    if (DEFS_KEY in prop) {
      const defs = prop[DEFS_KEY] as Record<string, JSONSchema.BaseSchema>;
      delete prop[DEFS_KEY];

      if (!addedDefs) {
        for (const defSchemaId of Object.keys(defs)) {
          if (defSchemaId.startsWith('__schema')) {
            defRenames[defSchemaId] = `${newSchemaName}${defSchemaId}`;
          }
        }

        for (const [defSchemaId, defSchema] of Object.entries(defs)) {
          const fixedDef = fixAllRefs({
            schema: defSchema,
            rootSchemaName: newSchemaName,
            defRenames,
          });
          const newDefSchemaKey = defRenames[defSchemaId] ?? defSchemaId;
          registerSchema(
            additionalNewSchemas,
            newDefSchemaKey,
            fixedDef as DtoSchema,
          );
        }

        addedDefs = true;
      }
    }
  }

  if (hasRefs) {
    newOpenapiSchema = fixAllRefs({
      schema: newOpenapiSchema as JSONSchema.BaseSchema,
      rootSchemaName: newSchemaName,
      defRenames,
    }) as typeof newOpenapiSchema;
  }

  const rootProp = newOpenapiSchema.properties?.root as
    | Record<string, unknown>
    | undefined;
  if (rootProp && UNWRAP_ROOT_KEY in rootProp) {
    const replaceRoot = rootProp[UNWRAP_ROOT_KEY];
    delete rootProp[UNWRAP_ROOT_KEY];
    if (replaceRoot) {
      newOpenapiSchema = rootProp as unknown as typeof newOpenapiSchema;
    }
  }

  if (
    Object.hasOwn(additionalNewSchemas, newSchemaName) &&
    !isDeepStrictEqual(additionalNewSchemas[newSchemaName], newOpenapiSchema)
  ) {
    throw new Error(
      `[cleanupOpenApiDoc] Found multiple schemas with name \`${newSchemaName}\`. Please review your schemas to ensure that you are not using the same schema name for different schemas.`,
    );
  }

  return {
    newSchema: newOpenapiSchema,
    newSchemaName,
    additionalNewSchemas,
  };
}

function fixParameter(parameterInput: OpenAPIParameter): OpenAPIParameter {
  const parameter = structuredClone(parameterInput);
  const rawParam = parameter as unknown as Record<string, unknown>;

  if (EMPTY_TYPE_KEY in rawParam) {
    if (
      rawParam[EMPTY_TYPE_KEY] &&
      'schema' in parameter &&
      parameter.schema &&
      'type' in parameter.schema
    ) {
      delete parameter.schema.type;
    }
    delete rawParam[EMPTY_TYPE_KEY];
  }

  if (TYPE_KEY in rawParam) {
    if ('schema' in parameter && parameter.schema) {
      Object.assign(parameter.schema, { type: rawParam[TYPE_KEY] });
    }
    delete rawParam[TYPE_KEY];
  }

  if (UNWRAP_ROOT_KEY in rawParam) {
    throw new Error(
      '[cleanupOpenApiDoc] Query or url parameters must be an object type',
    );
  }

  for (const key of EXTRA_PARAM_SCHEMA_KEYS) {
    if (key in rawParam && 'schema' in parameter && parameter.schema) {
      Object.assign(parameter.schema, { [key]: rawParam[key] });
      delete rawParam[key];
    }
  }

  delete rawParam[PARENT_ID_KEY];
  delete rawParam[PARENT_METADATA_KEY];
  delete rawParam[PARENT_ADDITIONAL_PROPERTIES_KEY];

  if (PARENT_HAS_REFS_KEY in rawParam) {
    delete rawParam[PARENT_HAS_REFS_KEY];

    if ('schema' in parameter && parameter.schema) {
      try {
        parameter.schema = fixAllRefs({
          schema: parameter.schema as JSONSchema.BaseSchema,
        }) as typeof parameter.schema;
      } catch (err) {
        if (err instanceof Error && err.message.startsWith('[fixAllRefs]')) {
          throw new Error(
            '[cleanupOpenApiDoc] Recursive schemas are not supported for parameters',
            { cause: err },
          );
        }
        throw err;
      }
    }
  }

  return parameter;
}
